def _analyze_with_extras(code, filename, concrete_inputs=None):
    local_analyzer = CodeAnalyzer()
    result = local_analyzer.analyze(code, filename, concrete_inputs)
    language = result.get('language', 'unknown')
    result['issues'] = [_issue_problem_only(issue) for issue in (result.get('issues') or [])]

    ai_discovery_result = {
        **result,
        'optimizations': [],
        'transformed_code': {'available': False, 'code': None},
    }
    enhanced_optimizations = enhance_optimizations_with_ai(ai_discovery_result, code, language)
    ai_only_optimizations = [
        opt for opt in enhanced_optimizations
        if opt.get('ai_generated') and opt.get('example')
    ]
    result['optimizations'] = ai_only_optimizations

    ai_optimization = next(
        (opt for opt in ai_only_optimizations if opt.get('ai_generated') and opt.get('example')),
        None
    )
    if ai_optimization:
        result['ai_transformed_code'] = {
            'available': True,
            'source': 'grok',
            'title': ai_optimization.get('title', 'AI Optimized Code'),
            'description': ai_optimization.get('solution') or ai_optimization.get('title', ''),
            'complexity_before': ai_optimization.get('complexity_before'),
            'complexity_after': ai_optimization.get('complexity_after'),
            'code': ai_optimization.get('example'),
            'notes': ai_optimization.get('ai_note', 'Generated by AI from analyzer-detected expensive function facts.'),
        }
        _attach_grok_solution_to_issue(result, ai_optimization)
    else:
        result['ai_transformed_code'] = {
            'available': False,
            'source': 'grok_discovery',
            'reason': (
                'Grok did not return a verified same-behavior lower-complexity rewrite '
                'for the detected expensive functions.'
            ),
        }

    result['transformed_code'] = {
        'available': False,
        'reason': 'Only Grok-discovered optimized code is displayed to users.',
        'complexity_before': result.get('time_complexity'),
        'complexity_after': 'requires_grok',
        'code': None,
    }
    result['suggestions'] = []
    result['rating'] = local_analyzer.calculate_rating(result)
    result['ai_explanation'] = get_ai_explanation(result, code, language)
    if not result.get('optimizations'):
        result['ai_explanation']['top_optimization'] = ''

    call_graph_report = local_analyzer.call_graph_analyzer.get_call_chain_report(
        code,
        local_analyzer.last_func_complexities,
        language,
        local_analyzer.last_func_own_complexities
    )
    result['call_chain_report'] = call_graph_report

    result['function_explanations'] = get_function_level_explanations(
        local_analyzer.last_func_complexities,
        call_graph_report,
        language,
        local_analyzer.last_func_complexity_details,
        code
    )

    return result


def _issue_problem_only(issue):
    cleaned = dict(issue or {})
    message = str(cleaned.get('message') or '').strip()
    parts = re.split(r'\s+(?:—|â€”|-)\s+', message, maxsplit=1)
    if len(parts) == 2 and re.match(
        r'(?i)(?:add|use|replace|consider|can be optimized|optimi[sz]e|try)\b',
        parts[1].strip()
    ):
        message = parts[0].strip()
    cleaned['message'] = message
    return cleaned


def _attach_grok_solution_to_issue(result, ai_optimization):
    if not result.get('issues') or not ai_optimization.get('example'):
        return

    solution = {
        'title': ai_optimization.get('title') or 'Grok optimized rewrite',
        'description': ai_optimization.get('solution') or ai_optimization.get('problem') or '',
        'complexity_before': ai_optimization.get('complexity_before'),
        'complexity_after': ai_optimization.get('complexity_after'),
        'code': ai_optimization.get('example'),
        'notes': ai_optimization.get('ai_note') or 'Generated by Grok from analyzer-detected expensive function facts.',
        'source': ai_optimization.get('source', 'grok'),
    }

    target_function = str(ai_optimization.get('function') or '').lower()
    selected = None
    if target_function:
        for issue in result['issues']:
            text = f"{issue.get('message', '')} {issue.get('type', '')}".lower()
            if target_function in text:
                selected = issue
                break
    if selected is None:
        selected = next(
            (issue for issue in result['issues'] if issue.get('type') == 'performance'),
            result['issues'][0],
        )
    selected['grok_solution'] = solution


def _build_batch_summary(results, source='batch'):
    analyzer = CodeAnalyzer()
    complexities = [
        item.get('result', {}).get('time_complexity')
        for item in results
        if item.get('result', {}).get('time_complexity')
    ]
    worst_time = analyzer._max_complexity(complexities) if complexities else 'O(unknown)'
    quadratic_rank = analyzer._complexity_rank(analyzer._parse_complexity_string('O(n²)'))

    languages = {}
    confidence_counts = {'high': 0, 'medium': 0, 'low': 0, 'unknown': 0}
    low_confidence_files = []
    high_complexity_files = []
    unknown_complexity_files = []
    hotspot_count = 0

    for item in results:
        filename = item.get('filename', 'Unknown File')
        result = item.get('result') or {}
        language = result.get('language', 'unknown')
        languages[language] = languages.get(language, 0) + 1

        confidence = result.get('analysis_confidence') or {}
        level = confidence.get('time', 'unknown')
        confidence_counts[level] = confidence_counts.get(level, 0) + 1
        if level in ('low', 'medium'):
            low_confidence_files.append({
                'filename': filename,
                'confidence': level,
                'reason': confidence.get('reason', ''),
            })

        complexity = result.get('time_complexity', 'O(unknown)')
        if complexity == 'O(unknown)':
            unknown_complexity_files.append(filename)
        rank = analyzer._complexity_rank(analyzer._parse_complexity_string(complexity))
        if rank >= quadratic_rank:
            high_complexity_files.append({
                'filename': filename,
                'time_complexity': complexity,
                'rating': result.get('rating', 0),
            })
        hotspot_count += len(result.get('hotspots') or [])

    max_files = MAX_BATCH_FILES if source == 'zip' else MAX_GITHUB_FILES if source == 'github' else None
    return {
        'source': source,
        'languages': languages,
        'worst_time_complexity': worst_time,
        'confidence_counts': confidence_counts,
        'needs_review_files': low_confidence_files[:10],
        'unknown_complexity_files': unknown_complexity_files[:10],
        'high_complexity_files': high_complexity_files[:10],
        'hotspot_count': hotspot_count,
        'analysis_limits': {
            'max_files': max_files,
            'max_source_bytes_per_file': MAX_SOURCE_BYTES,
            'note': 'Batch analysis summarizes selected supported files; dependency and cross-repo runtime behavior may still need review.',
        },
    }


